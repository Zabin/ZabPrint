# Fallback: lowercase resolves to uppercase glyph.
def _glyph(ch: str) -> tuple[int, ...]:
    if ch in _GLYPHS:
        return _GLYPHS[ch]
    if 'a' <= ch <= 'z':
        return _GLYPHS[ch.upper()]
    return (0, 0, 0x66, 0x18, 0x66, 0x00, 0x18, 0x00)  # generic ?-ish


def glyph_indices(ch: str, *, fg: int = 1, bg: int = 0) -> np.ndarray:
    """8x8 array of palette indices for one character."""
    rows = _glyph(ch)
    out = np.full((8, 8), bg, dtype=np.uint8)
    for y, byte in enumerate(rows):
        for x in range(8):
            if byte & (0x80 >> x):
                out[y, x] = fg
    return out


def font_sheet_indices(*, fg: int = 1, bg: int = 0) -> np.ndarray:
    """Render a 16-glyph-wide, 6-row-tall (96 printable ASCII chars) sheet."""
    out = np.full((6 * 8, 16 * 8), bg, dtype=np.uint8)
    for code in range(32, 128):
        idx = code - 32
        row = idx // 16
        col = idx % 16
        glyph = glyph_indices(chr(code), fg=fg, bg=bg)
        out[row * 8:row * 8 + 8, col * 8:col * 8 + 8] = glyph
    return out
